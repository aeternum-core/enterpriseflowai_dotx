from typing import List, Dict, Set
from app.schemas.contracts import TaskDAG, WorkflowTask, WorkerRole

VALID_WORKER_ROLES = {
    "DOCUMENT_AND_DATA_WORKER",
    "BUSINESS_OPERATIONS_WORKER",
    "IT_AND_INTEGRATION_WORKER",
    "PLANNER",
    "POLICY_SENTINEL"
}

VALID_ACTION_TYPES = {
    # Document & Data
    "EXTRACT_DOCUMENTS",
    "VALIDATE_DATA",
    "DEDUPLICATE_LEDGER",
    "COMPARE_QUOTATIONS",
    "NORMALIZE_RECORDS",
    # Business Operations
    "CREATE_EMPLOYEE_RECORD",
    "EXECUTE_DISBURSEMENT",
    "CREATE_PURCHASE_ORDER",
    "RESOLVE_CUSTOMER_DISPUTE",
    "UPDATE_BUSINESS_RECORDS",
    # IT & Integration
    "PROVISION_ACCOUNTS",
    "ELEVATE_JIT_ACCESS",
    "REMEDIATE_INCIDENT",
    "DISPATCH_COMMUNICATION"
}

class DAGValidationError(Exception):
    def __init__(self, errors: List[str]):
        super().__init__("; ".join(errors))
        self.errors = errors

class DAGValidator:
    """
    Deterministic DAG validation engine.
    Ensures that task graphs generated by Level 2 Planner comply with
    dependency constraints, worker roles, acyclicity, and execution rules.
    """

    @classmethod
    def validate(cls, dag: TaskDAG) -> TaskDAG:
        errors: List[str] = []
        task_ids: Set[str] = set()

        if not dag.tasks:
            errors.append("Task DAG contains zero tasks.")
            dag.is_valid = False
            dag.validation_errors = errors
            return dag

        # 1. Unique Task IDs & Role/Action Validation
        for task in dag.tasks:
            if not task.task_id:
                errors.append("Encountered task with empty task_id.")
            elif task.task_id in task_ids:
                errors.append(f"Duplicate task_id detected: '{task.task_id}'.")
            task_ids.add(task.task_id)

            if task.worker_role not in VALID_WORKER_ROLES:
                errors.append(f"Task '{task.task_id}' assigned invalid worker_role '{task.worker_role}'.")

            if task.action_type not in VALID_ACTION_TYPES:
                errors.append(f"Task '{task.task_id}' specifies unknown action_type '{task.action_type}'.")

        # 2. Dependency Existence & No Self-Dependency
        for task in dag.tasks:
            for dep in task.dependencies:
                if dep == task.task_id:
                    errors.append(f"Task '{task.task_id}' has self-dependency on itself.")
                if dep not in task_ids:
                    errors.append(f"Task '{task.task_id}' depends on non-existent task '{dep}'.")

        # 3. Cycle Detection via DFS (Graph Acyclicity)
        adj: Dict[str, List[str]] = {t.task_id: list(t.dependencies) for t in dag.tasks}
        visited: Dict[str, int] = {t.task_id: 0 for t in dag.tasks} # 0=unvisited, 1=visiting, 2=visited

        def has_cycle(u: str) -> bool:
            visited[u] = 1 # Visiting
            for v in adj.get(u, []):
                if v in visited:
                    if visited[v] == 1:
                        return True
                    if visited[v] == 0 and has_cycle(v):
                        return True
            visited[u] = 2 # Visited
            return False

        for t_id in task_ids:
            if visited[t_id] == 0:
                if has_cycle(t_id):
                    errors.append(f"Cycle detected in task dependency graph involving '{t_id}'.")
                    break

        if errors:
            dag.is_valid = False
            dag.validation_errors = errors
        else:
            dag.is_valid = True
            dag.validation_errors = []

        return dag

dag_validator = DAGValidator()
